use ppn::error::{CliError, ErrorKind};
use ppn::output::CommandResult;

#[derive(clap::Subcommand)]
pub enum Command {
    /// Return a simulated CLI error.
    #[command(after_help = "Examples:\n  ppn debug fail not_found --json")]
    Fail {
        /// Stable error code to simulate.
        #[arg(value_enum)]
        code: ErrorKind,
    },
}

pub fn run(command: Command) -> Result<CommandResult, CliError> {
    match command {
        Command::Fail { code } => Err(CliError::new(code, "Simulated command failure.")
            .with_hint("This diagnostic was generated by ppn debug fail.")),
    }
}
