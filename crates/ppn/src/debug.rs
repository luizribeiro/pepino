use ppn::error::{CliError, ErrorKind};
use ppn::output::{CommandResult, Render};
use ppn::terminal::Terminal;
use serde::Serialize;

#[derive(clap::Subcommand)]
pub enum Command {
    /// Return a simulated CLI error.
    #[command(after_help = "Examples:\n  ppn debug fail not_found --json")]
    Fail {
        /// Stable error code to simulate.
        #[arg(value_enum)]
        code: ErrorKind,
    },
    /// Exercise confirmation handling.
    #[command(after_help = "Examples:\n  ppn debug confirm --yes")]
    Confirm,
}

pub fn run(command: Command, terminal: &Terminal) -> Result<CommandResult, CliError> {
    match command {
        Command::Fail { code } => Err(CliError::new(code, "Simulated command failure.")
            .with_hint("This diagnostic was generated by ppn debug fail.")),
        Command::Confirm => {
            let confirmed = terminal.confirm("Archive the release board?")?;
            Ok(CommandResult::document(Confirmation { confirmed }))
        }
    }
}

#[derive(Serialize)]
struct Confirmation {
    confirmed: bool,
}

impl Render for Confirmation {
    fn human(&self, _: &Terminal) -> String {
        if self.confirmed {
            "Confirmed"
        } else {
            "Declined"
        }
        .into()
    }
}
