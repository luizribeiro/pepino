use std::path::PathBuf;

use ppn::error::{CliError, ErrorKind};
use ppn::help_tree::example_help;
use ppn::input::read_text;
use ppn::output::{CommandResult, Render};
use ppn::terminal::{Context, Terminal};
use serde_json::{Map, Value, json};

#[derive(clap::Subcommand)]
pub enum Command {
    /// Return a simulated CLI error.
    #[command(after_help = example_help(&["ppn debug fail not_found --json"]))]
    Fail {
        /// Stable error code to simulate.
        #[arg(value_enum)]
        code: ErrorKind,
    },
    /// Exercise confirmation handling.
    #[command(after_help = example_help(&["ppn debug confirm --yes"]))]
    Confirm,
    /// Read text from the command line, stdin, or a file.
    #[command(after_help = example_help(&["ppn debug input --from-file release-notes.txt"]))]
    Input {
        /// Text or - to read stdin.
        #[arg(value_name = "TEXT")]
        value: Option<String>,
        /// Read text from a file.
        #[arg(long, conflicts_with = "value")]
        from_file: Option<PathBuf>,
    },
}

pub fn run(context: &Context, command: Command) -> Result<CommandResult, CliError> {
    match command {
        Command::Fail { code } => Err(CliError::new(code, "Simulated command failure.")
            .with_hint("This diagnostic was generated by ppn debug fail.")),
        Command::Confirm => {
            let confirmed = context.confirm("Archive the release board?")?;
            Ok(CommandResult::document(Confirmation { confirmed }))
        }
        Command::Input { value, from_file } => {
            let text = read_text(value, from_file.as_deref())?;
            Ok(CommandResult::document(Text { text }))
        }
    }
}

struct Confirmation {
    confirmed: bool,
}

impl Render for Confirmation {
    fn human(&self, _: &Terminal) -> String {
        if self.confirmed {
            "Confirmed"
        } else {
            "Declined"
        }
        .into()
    }

    fn json_fields(self) -> Map<String, Value> {
        Map::from_iter([("confirmed".into(), json!(self.confirmed))])
    }
}

struct Text {
    text: String,
}

impl Render for Text {
    fn human(&self, _: &Terminal) -> String {
        self.text.clone()
    }

    fn json_fields(self) -> Map<String, Value> {
        Map::from_iter([("text".into(), self.text.into())])
    }
}
